#: Not in Simple Icons: a lettermark in the brand's own colour (honest fallback, not a logo).
LETTERMARKS = {
    "zabbix": ("Zabbix", "D40000", "Z"),
    "azure": ("Microsoft Azure", "0078D4", "Az"),
    "action1": ("Action1", "F26722", "A1"),
}


def luminance(hex6: str) -> float:
    def ch(c: int) -> float:
        v = c / 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex6[i : i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def main(pkg: Path) -> None:
    meta = {i["slug"]: i for i in json.loads((pkg / "data" / "simple-icons.json").read_text())}
    out: dict[str, dict[str, str]] = {}
    for slug in SLUGS:
        svg = (pkg / "icons" / f"{slug}.svg").read_text(encoding="utf-8")
        m = re.search(r'<path d="([^"]+)"', svg)
        if m is None or slug not in meta:
            raise SystemExit(f"{slug}: no path")
        out[slug] = {"title": meta[slug]["title"], "hex": meta[slug]["hex"].upper(), "path": m[1]}
    for slug, (title, hex6, text) in LETTERMARKS.items():
        out[slug] = {"title": title, "hex": hex6, "text": text}
    out = dict(sorted(out.items(), key=lambda kv: kv[1]["title"].lower()))
    (WEB / "brands.json").write_text(json.dumps(out, indent=0, ensure_ascii=False) + "\n")

    css = [
        "/* Generated by scripts/vendor_brands.py from Simple Icons (CC0-1.0). Do not edit. */",
        "/* --b is the brand colour; very dark/light brands get a readable variant per theme. */",
    ]
    dark = []
    for slug, b in out.items():
        lum = luminance(b["hex"])
        light_c = (
            f"#{b['hex']}" if lum < 0.75 else "color-mix(in srgb, #" + b["hex"] + " 55%, #000)"
        )
        css.append(f".b-{slug}{{--b:{light_c}}}")
        if lum < 0.09:
            dark.append(f".b-{slug}{{--b:color-mix(in srgb, #{b['hex']} 45%, #fff)}}")
    if dark:
        css.append(
            "@media (prefers-color-scheme: dark){:root:not([data-theme=light]) "
            + "".join(dark).replace("}.b-", "}:root:not([data-theme=light]) .b-")
            + "}"
        )
        css.append(
            ":root[data-theme=dark] " + "".join(dark).replace("}.b-", "}:root[data-theme=dark] .b-")
        )
    (WEB / "static" / "brands.css").write_text("\n".join(css) + "\n")
    print(f"{len(out)} brands")  # noqa: T201


if __name__ == "__main__":
    main(Path(sys.argv[1]))
