"""Render target-side setup artifacts from `ProbeSection` (single source of truth, ADR-002).

`atlas targets render` writes these to docs/targets/ for the owner to review and install.
A test asserts the committed copies match, so the allowlist cannot drift between the
collector, the gate, sudoers and the probe.
"""

import hashlib
import re
from importlib.resources import files
from typing import Final

from homelab_atlas.security.allowlist import PROBE_COMMANDS, ProbeSection

PROBE_VERSION: Final = "1.4.0"
PROBE_PATH: Final = "/usr/local/libexec/atlas-probe"
GATE_PATH: Final = "/usr/local/libexec/atlas-probe-gate"
SUDO_PATH: Final = "/usr/bin/sudo"
PROBE_USER: Final = "atlas-ro"
#: Sections the probe implements (all of them; kept for the gate template and docs).
IMPLEMENTED: Final = frozenset(ProbeSection)

_PATH_RE: Final = re.compile(r"/[A-Za-z0-9._/-]+")
_USER_RE: Final = re.compile(r"[a-z_][a-z0-9_-]{0,31}")


def _template(name: str) -> str:
    return (files("homelab_atlas.probe") / "templates" / name).read_text(encoding="utf-8")


def _fill(text: str, **values: str) -> bytes:
    for key, value in values.items():
        text = text.replace(f"@@{key}@@", value)
    if "@@" in text:
        raise ValueError("unrendered placeholder")
    return text.replace("\r\n", "\n").encode("utf-8")


def _check_path(path: str) -> str:
    if not _PATH_RE.fullmatch(path) or ".." in path:
        raise ValueError(f"bad absolute path: {path!r}")
    return path


def render_probe() -> bytes:
    return _fill(_template("atlas-probe.sh"), VERSION=PROBE_VERSION, PROBE=PROBE_PATH)


def probe_sha256() -> str:
    return hashlib.sha256(render_probe()).hexdigest()


def render_gate(*, sudo: str = SUDO_PATH, probe: str = PROBE_PATH, user: str = PROBE_USER) -> bytes:
    cases = "\n".join(
        f'    "{PROBE_COMMANDS[s]}")\n        section={s.value}\n        ;;'
        for s in sorted(ProbeSection, key=lambda s: s.value)
    )
    return _fill(
        _template("atlas-probe-gate.sh"),
        VERSION=PROBE_VERSION,
        SUDO=_check_path(sudo),
        PROBE=_check_path(probe),
        USER=user,
        CASES=cases,
    )


def render_sudoers(*, user: str = PROBE_USER, probe: str = PROBE_PATH) -> bytes:
    if not _USER_RE.fullmatch(user) or user == "root":
        raise ValueError("bad user")
    probe = _check_path(probe)
    commands = ", \\\n    ".join(
        f"{probe} {s.value}" for s in sorted(ProbeSection, key=lambda s: s.value)
    )
    return (
        f"# /etc/sudoers.d/{user} -- generated by `atlas targets render` (probe {PROBE_VERSION}).\n"
        "# Install root:root 0440 and validate with: visudo -cf /etc/sudoers.d/" + user + "\n"
        "# Exact argv only: no wildcards, so sudo refuses any other argument.\n"
        f"Defaults:{user} !requiretty, !lecture, env_reset, "
        'secure_path="/usr/sbin:/usr/bin:/sbin:/bin"\n'
        f"Cmnd_Alias ATLAS_PROBE = {commands}\n"
        f"{user} ALL=(root) NOPASSWD: ATLAS_PROBE\n"
    ).encode()


def render_authorized_keys(*, gate: str = GATE_PATH) -> bytes:
    return (
        "# ~atlas-ro/.ssh/authorized_keys -- replace <COLLECTOR_IP> and <PUBLIC_KEY>.\n"
        "# `restrict` disables pty, agent/port/X11 forwarding and ~/.ssh/rc; the forced\n"
        "# command ignores whatever the client asks for except the gate's exact strings.\n"
        f'restrict,from="<COLLECTOR_IP>",command="{_check_path(gate)}" '
        "ssh-ed25519 <PUBLIC_KEY> atlas-collector\n"
    ).encode()


def _readme(sums: dict[str, str]) -> bytes:
    sections = ", ".join(f"`{s.value}`" for s in sorted(IMPLEMENTED, key=lambda s: s.value))
    lines = [
        "# Target setup artifacts (generated, review before installing)",
        "",
        f"Probe version **{PROBE_VERSION}**. Regenerate with `uv run atlas targets render`.",
        "Do not edit these files: the collector pins the probe's SHA-256 and `atlas doctor`",
        "reports any mismatch. Step-by-step instructions:",
        "[docs/SETUP-TARGETS.md](../SETUP-TARGETS.md).",
        "",
        "| File | Install as | Owner / mode |",
        "|---|---|---|",
        f"| `atlas-probe` | `{PROBE_PATH}` | root:root 0755 |",
        f"| `atlas-probe-gate` | `{GATE_PATH}` | root:root 0755 |",
        f"| `sudoers.{PROBE_USER}` | `/etc/sudoers.d/{PROBE_USER}` | root:root 0440 (visudo -cf) |",
        f"| `authorized_keys.example` | `~{PROBE_USER}/.ssh/authorized_keys` | "
        f"{PROBE_USER} 0600, dir 0700, owned by root is fine |",
        "",
        f"User: `{PROBE_USER}`, a system account with no password (`passwd -l`), no docker group, "
        "no other sudo rights.",
        f"Implemented sections: {sections}. `pi` needs Raspberry Pi OS (vcgencmd).",
        "",
        "Debian/Ubuntu only (systemd ≥ 246, iproute2, util-linux, dpkg).",
        "",
        "## SHA-256",
        "",
        "```",
        *(f"{digest}  {name}" for name, digest in sorted(sums.items())),
        "```",
        "",
    ]
    return "\n".join(lines).encode()


def render_all() -> dict[str, bytes]:
    out = {
        "atlas-probe": render_probe(),
        "atlas-probe-gate": render_gate(),
        f"sudoers.{PROBE_USER}": render_sudoers(),
        "authorized_keys.example": render_authorized_keys(),
    }
    sums = {name: hashlib.sha256(data).hexdigest() for name, data in out.items()}
    out["README.md"] = _readme(sums)
    return out
